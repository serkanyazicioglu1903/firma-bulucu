"""OFFLINE-ONLY two-legal-entity PostgreSQL DDL rehearsal plan.

This module has NO database connector, environment lookup, CLI entrypoint,
migration runner, and NO customer data. Only explicitly isolated tests may
execute these statements. Never apply them to ct_app production without a
separate approved backup, backfill, permission review and rollback plan.

Phase A adds nullable legal_entity_id references without assigning ownership.
Phase B is a separate, intentionally fail-closed enforcement step AFTER every
existing row is assigned a verified owner and application reads/writes have
been made company-scoped. Creating these columns alone does NOT prove tenancy.
"""
from scripts.postgres_company_scope import CRITICAL_TABLES

# Fixed, reviewed graph: (child table, parent fk, parent table).
# Shared customer/product master data are not assumed to be legal entities.
OWNED_RELATIONSHIPS = (
    ("shipments", "purchase_order_id", "purchase_orders"),
    ("inventory_lots", "purchase_order_id", "purchase_orders"),
    ("inventory_lots", "shipment_id", "shipments"),
    ("quality_cases", "purchase_order_id", "purchase_orders"),
    ("quality_cases", "shipment_id", "shipments"),
    ("quality_cases", "inventory_lot_id", "inventory_lots"),
    ("payables", "purchase_order_id", "purchase_orders"),
    ("finance_transactions", "receivable_id", "receivables"),
    ("finance_transactions", "payable_id", "payables"),
    ("finance_transactions", "account_id", "cash_accounts"),
)
PARENTS = tuple(dict.fromkeys(parent for _, _, parent in OWNED_RELATIONSHIPS))


def additive_ddl():
    """Phase A: return reviewable SQL, NEVER execute it.

    Backfill is deliberately absent: guessing record ownership is unsafe.
    A nullable owner field is a MIGRATION INTERMEDIATE, not go-live readiness.
    """
    statements = [
        'CREATE TABLE "ct_app"."legal_entities" ('
        'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,'
        'code TEXT NOT NULL UNIQUE, legal_name TEXT NOT NULL,'
        'active BOOLEAN NOT NULL DEFAULT TRUE,'
        'CONSTRAINT legal_entities_code_nonempty CHECK '
        "(length(btrim(code)) BETWEEN 2 AND 60))",
    ]
    for table in CRITICAL_TABLES:
        statements.append(
            f'ALTER TABLE "ct_app"."{table}" '
            'ADD COLUMN legal_entity_id BIGINT NULL REFERENCES '
            '"ct_app"."legal_entities"(id)'
        )
        statements.append(
            f'CREATE INDEX "idx_{table}_legal_entity_id" '
            f'ON "ct_app"."{table}" (legal_entity_id)'
        )
    return tuple(statements)


def enforcement_ddl():
    """Phase B: require owners + reject cross-company relational links.

    Must fail if any prior record is still unassigned. Applying this AFTER
    uncontrolled application writes could be unsafe; require an offline
    migration window and a reviewed per-entity authorization layer first.
    """
    statements = []
    for parent in PARENTS:
        statements.append(
            f'CREATE UNIQUE INDEX "uq_{parent}_id_legal_entity" '
            f'ON "ct_app"."{parent}" (id, legal_entity_id)'
        )
    for table in CRITICAL_TABLES:
        statements.append(
            f'ALTER TABLE "ct_app"."{table}" '
            'ALTER COLUMN legal_entity_id SET NOT NULL'
        )
    for child, foreign_key, parent in OWNED_RELATIONSHIPS:
        statements.append(
            f'ALTER TABLE "ct_app"."{child}" '
            f'ADD CONSTRAINT "fk_{child}_{foreign_key}_company" '
            f'FOREIGN KEY ({foreign_key}, legal_entity_id) '
            f'REFERENCES "ct_app"."{parent}" (id, legal_entity_id)'
        )
    return tuple(statements)
