_ALLOWED = {
    "create_purchase_order": frozenset(("PURCHASING", "ADMIN")),
    "create_shipment": frozenset(("PURCHASING", "ADMIN")),
    "create_payable": frozenset(("FINANCE", "ADMIN")),
}
_ACTION_TABLE = {
    "create_purchase_order": "purchase_orders",
    "create_shipment": "shipments",
    "create_payable": "payables",
}


class ScopedWriteDenied(Exception):
    def __init__(self, code="forbidden"):
        super().__init__(code)
        self.code = code


def rehearsal_extra_ddl():
    """Reviewed SQL returned as text; this function NEVER executes it.

    No default write access; no company/user/warehouse rows are seeded.
    All DDL must be inside a disposable CI test transaction, rolled back.
    """
    return (
        'CREATE TABLE "ct_app"."company_write_grants" ('
        'principal_id TEXT NOT NULL, '
        'legal_entity_id BIGINT NOT NULL REFERENCES "ct_app"."legal_entities"(id), '
        'can_write BOOLEAN NOT NULL DEFAULT FALSE, '
        'PRIMARY KEY (principal_id,legal_entity_id))',
        'CREATE TABLE "ct_app"."company_warehouse_scope" ('
        'warehouse_id BIGINT NOT NULL REFERENCES "ct_app"."warehouses"(id), '
        'legal_entity_id BIGINT NOT NULL REFERENCES "ct_app"."legal_entities"(id), '
        'PRIMARY KEY (warehouse_id,legal_entity_id))',
        'CREATE TABLE "ct_app"."company_operation_audit" ('
        'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, '
        'principal_id TEXT NOT NULL, '
        'legal_entity_id BIGINT NOT NULL REFERENCES "ct_app"."legal_entities"(id), '
        'operation TEXT NOT NULL, target_table TEXT NOT NULL, '
        'record_id BIGINT NOT NULL, created_at TIMESTAMPTZ DEFAULT now())',
    )


def _checked_text(value, max_length=250):
    if not isinstance(value, str):
        raise ScopedWriteDenied("invalid_input")
    cleaned = value.strip()
    if not cleaned or len(cleaned) > max_length:
        raise ScopedWriteDenied("invalid_input")
    return cleaned


def _checked_id(value):
    if type(value) is not int or value <= 0:
        raise ScopedWriteDenied("invalid_input")
    return value


def _positive(value):
    if isinstance(value, bool):
        raise ScopedWriteDenied("invalid_input")
    try:
        number = Decimal(str(value))
    except (InvalidOperation, ValueError, TypeError):
        raise ScopedWriteDenied("invalid_input") from None
    if not number.is_finite() or number <= 0:
        raise ScopedWriteDenied("invalid_input")
    return number


def _money(value):
    currency = _checked_text(value, max_length=3).upper()
    if currency not in ("EUR", "USD", "GBP", "TRY"):
        raise ScopedWriteDenied("invalid_input")
    return currency


def _calendar_date(value):
    try:
        return date.fromisoformat(_checked_text(value, 10)).isoformat()
    except ValueError:
        raise ScopedWriteDenied("invalid_input") from None


def _valid_disposable_test_target(url):
    """A CI-only second gate. Even a misconfigured feature flag won't pass."""
    if not isinstance(url, str):
        return False
    if os.environ.get("CT_LOCAL_POSTGRES_TEST") != "1":
        return False
    if os.environ.get("AS_CONTROL_TOWER_PG_WRITES_ENABLED") != "1":
        return False
    if url != os.environ.get("CT_TEST_DATABASE_URL", ""):
        return False
    try:
        parsed = urlsplit(url)
        return (
            parsed.scheme in ("postgres", "postgresql")
            and parsed.hostname in ("localhost", "127.0.0.1")
            and parsed.port == 5432
            and parsed.username == CI_USER
            and parsed.path == "/" + CI_DATABASE
            and parsed.query == ""
            and sslmode_for(url) == "disable"
        )
    except ValueError:
        return False


def _owner_and_writer(cur, principal_id, company_code):
    """Lock read + write grants and legal entity against concurrent revocation."""
    status, company_id = authorize_company_on_cursor(
        cur, principal_id, company_code
    )
    if status != "ok":
        raise ScopedWriteDenied(status)

    cur.execute(
        "SELECT to_regclass('ct_app.company_write_grants') IS NOT NULL, "
        "to_regclass('ct_app.company_warehouse_scope') IS NOT NULL, "
        "to_regclass('ct_app.company_operation_audit') IS NOT NULL"
    )
    if tuple(cur.fetchone()) != (True, True, True):
        raise ScopedWriteDenied("not_ready")
    cur.execute(
        'SELECT e.id FROM "ct_app"."legal_entities" e '
        'JOIN "ct_app"."company_read_grants" r ON r.legal_entity_id=e.id '
        'JOIN "ct_app"."company_write_grants" w ON w.legal_entity_id=e.id '
        'WHERE e.id=%s AND e.code=%s AND e.active=TRUE '
        'AND r.principal_id=%s AND r.can_read=TRUE '
        'AND w.principal_id=%s AND w.can_write=TRUE '
        'FOR SHARE OF e,r,w',
        (company_id, company_code, principal_id, principal_id),
    )
    if cur.fetchone() is None:
        raise ScopedWriteDenied()
    return company_id


def _assigned_warehouse(cur, company_id, warehouse_id):
    cur.execute(
        'SELECT w.id FROM "ct_app"."warehouses" w '
        'JOIN "ct_app"."company_warehouse_scope" x '
        'ON x.warehouse_id=w.id AND x.legal_entity_id=%s '
        'WHERE w.id=%s AND w.active=1 FOR SHARE OF w,x',
        (company_id, warehouse_id),
    )
    if cur.fetchone() is None:
        raise ScopedWriteDenied("wrong_company_warehouse")


def create_purchase_order_on_cursor(cur, company_id, *,
                                    po_number, supplier, product_id, warehouse_id,
                                    quantity_kg, unit_price, currency):
    """Insert a PO owned by the authorized company; shared product is reference-only."""
    number = _checked_text(po_number)
    vendor = _checked_text(supplier)
    prod = _checked_id(product_id)
    warehouse = _checked_id(warehouse_id)
    qty = _positive(quantity_kg)
    price = _positive(unit_price)
    curr = _money(currency)
    _assigned_warehouse(cur, company_id, warehouse)
    cur.execute(
        'SELECT name FROM "ct_app"."product_catalog" '
        'WHERE id=%s AND active=1 FOR SHARE',
        (prod,),
    )
    product = cur.fetchone()
    if product is None:
        raise ScopedWriteDenied("unknown_product")
    # Legacy schema has a global po_number; lock serializes duplicate checks.
    cur.execute(
        'SELECT pg_advisory_xact_lock(4601, hashtext(%s))', (number,),
    )
    cur.execute(
        'SELECT 1 FROM "ct_app"."purchase_orders" WHERE po_number=%s LIMIT 1',
        (number,),
    )
    if cur.fetchone() is not None:
        raise ScopedWriteDenied("duplicate_po")
    cur.execute(
        'INSERT INTO "ct_app"."purchase_orders" '
        '(po_number,supplier,product_id,product_name,quantity_kg,unit_price,'
        'currency,destination_warehouse_id,legal_entity_id) '
        'VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s) RETURNING id',
        (number,vendor,prod,product[0],qty,price,curr,warehouse,company_id),
    )
    return int(cur.fetchone()[0])


def create_shipment_on_cursor(cur, company_id, *,
                              purchase_order_id, shipment_ref, quantity_kg):
    po_id = _checked_id(purchase_order_id)
    reference = _checked_text(shipment_ref)
    qty = _positive(quantity_kg)
    cur.execute(
        'SELECT quantity_kg,status,destination_warehouse_id '
        'FROM "ct_app"."purchase_orders" '
        'WHERE id=%s AND legal_entity_id=%s FOR UPDATE',
        (po_id, company_id),
    )
    order = cur.fetchone()
    if order is None or order[1] == "İptal":
        raise ScopedWriteDenied("wrong_company_po")
    if order[2] is None:
        raise ScopedWriteDenied("warehouse_required")
    _assigned_warehouse(cur, company_id, int(order[2]))
    cur.execute(
        'SELECT COALESCE(SUM(quantity_kg),0) FROM "ct_app"."shipments" '
        "WHERE purchase_order_id=%s AND legal_entity_id=%s AND status!='İptal'",
        (po_id, company_id),
    )
    reserved = Decimal(str(cur.fetchone()[0]))
    if reserved + qty > Decimal(str(order[0])) + Decimal("0.001"):
        raise ScopedWriteDenied("over_shipment")
    cur.execute(
        'SELECT 1 FROM "ct_app"."shipments" '
        'WHERE purchase_order_id=%s AND legal_entity_id=%s '
        'AND shipment_ref=%s LIMIT 1',
        (po_id, company_id, reference),
    )
    if cur.fetchone() is not None:
        raise ScopedWriteDenied("duplicate_shipment")
    cur.execute(
        'INSERT INTO "ct_app"."shipments" '
        '(purchase_order_id,shipment_ref,quantity_kg,destination_warehouse_id,'
        'legal_entity_id) VALUES (%s,%s,%s,%s,%s) RETURNING id',
        (po_id,reference,qty,order[2],company_id),
    )
    return int(cur.fetchone()[0])


def create_payable_on_cursor(cur, company_id, *,
                             purchase_order_id, supplier, invoice_no,
                             due_date, amount, currency):
    po_id = _checked_id(purchase_order_id)
    vendor = _checked_text(supplier)
    invoice = _checked_text(invoice_no)
    due = _calendar_date(due_date)
    balance = _positive(amount)
    curr = _money(currency)
    cur.execute(
        'SELECT supplier,currency FROM "ct_app"."purchase_orders" '
        'WHERE id=%s AND legal_entity_id=%s FOR SHARE',
        (po_id, company_id),
    )
    order = cur.fetchone()
    if order is None or order[0] != vendor:
        raise ScopedWriteDenied("wrong_company_po")
    if order[1] != curr:
        raise ScopedWriteDenied("currency_mismatch")
    cur.execute(
        'SELECT pg_advisory_xact_lock(4602, hashtext(%s))',
        (str(company_id)+"|"+str(po_id)+"|"+invoice,),
    )
    cur.execute(
        'SELECT id FROM "ct_app"."payables" '
        'WHERE purchase_order_id=%s AND invoice_no=%s LIMIT 1',
        (po_id,invoice),
    )
    if cur.fetchone() is not None:
        raise ScopedWriteDenied("duplicate_invoice")
    cur.execute(
        'INSERT INTO "ct_app"."payables" '
        '(supplier,purchase_order_id,invoice_no,due_date,amount,currency,'
        'legal_entity_id) VALUES (%s,%s,%s,%s,%s,%s,%s) RETURNING id',
        (vendor,po_id,invoice,due,balance,curr,company_id),
    )
    return int(cur.fetchone()[0])


_ACTIONS = {
    "create_purchase_order": create_purchase_order_on_cursor,
    "create_shipment": create_shipment_on_cursor,
    "create_payable": create_payable_on_cursor,
}


def run_scoped_write_on_cursor(cur, principal_id, company_code, role,
                               operation, **inputs):
    """Testable atomic unit: authorization, write and audit in ONE transaction.

    Caller MUST own a disposable CI transaction; NEVER pass a production cursor.
    An error leaves the enclosing transaction to be rolled back.
    """
    if operation not in _ALLOWED or role not in _ALLOWED[operation]:
        raise ScopedWriteDenied()
    if (not isinstance(principal_id, str)
            or not PRINCIPAL_PATTERN.fullmatch(principal_id)
            or not isinstance(company_code, str)
            or company_code not in COMPANY_LABELS):
        raise ScopedWriteDenied()
    company_id = _owner_and_writer(cur, principal_id, company_code)
    record_id = _ACTIONS[operation](cur, company_id, **inputs)
    cur.execute(
        'INSERT INTO "ct_app"."company_operation_audit" '
        '(principal_id,legal_entity_id,operation,target_table,'
        'record_id) VALUES (%s,%s,%s,%s,%s)',
        (principal_id,company_id,operation,_ACTION_TABLE[operation],
         record_id),
    )
    return record_id


def run_scoped_write_rehearsal(url, principal_id, company_code, role,
                               operation, **inputs):
    """Standalone CI-only atomic adapter. NOT a production transaction API."""
    if operation not in _ALLOWED:
        return "forbidden", None
    if role not in _ALLOWED[operation]:
        return "forbidden", None
    if (not isinstance(principal_id, str)
            or not PRINCIPAL_PATTERN.fullmatch(principal_id)
            or company_code not in COMPANY_LABELS):
        return "forbidden", None
    if not _valid_disposable_test_target(url):
        return "disabled", None
    try:
        status, _ = validate_staging_structure(url, schema="ct_app")
        if status != "ok":
            return "schema_mismatch", None
        import psycopg
        with psycopg.connect(
            url, sslmode=sslmode_for(url), connect_timeout=8, autocommit=True,
        ) as conn:
            with conn.transaction():
                with conn.cursor() as cur:
                    cur.execute("SET LOCAL statement_timeout = '20s'")
                    cur.execute("SET LOCAL lock_timeout = '3s'")
                    cur.execute('SET LOCAL search_path TO "ct_app", pg_catalog')
                    record_id = run_scoped_write_on_cursor(
                        cur, principal_id, company_code, role, operation, **inputs
                    )
        return "ok", record_id
    except ScopedWriteDenied as err:
        return err.code, None
    except Exception:
        # May contain credentials or confidential SQL data: never return it.
        return "failed", None
