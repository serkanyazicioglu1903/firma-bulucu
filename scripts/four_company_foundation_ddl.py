"""Four-company database foundation, DDL PLAN ONLY. NOT a migration runner.

The current ct_app has twenty-six tables with no company ownership columns.
An actual four-company rollout needs explicit legal identity verification,
an independently owned map for every existing business row, least-privilege
roles and RLS, tested backup/restore, and legacy UI shutdown.

This proposal creates NO legal entities and NO user grants. It is intentionally
a staged proposal: nullable ownership references avoid guessing ownership,
and all company-specific read/write adapters stay blocked until enforcement.
Do not apply phase A directly to production: the migration guard will correctly
block legacy unscoped screens when it sees the first ownership column.
Only run DDL inside a disposable CI PostgreSQL transaction, rolled back.
"""
from scripts.postgres_company_full_coverage import REVIEW_GROUPS, _catalog_tables

_SCHEMA = "ct_app"
_PRIVATE_GROUPS = (
    "direct_owner_required",
    "parent_ownership_decision",
    "derived_ownership_decision",
)
_EXCLUDED = frozenset({"product_catalog", "audit_log", "system_settings"})


def private_company_tables():
    """23 tables need explicit legal ownership decision; do not infer owners.

    product_catalog is a candidate shared master, while audit_log and
    system_settings are internal access objects; all 3 need a separate
    reviewed company/security policy before production cutover.
    """
    names = [name for group in _PRIVATE_GROUPS
             for name in REVIEW_GROUPS[group]]
    expected = _catalog_tables()
    if (len(expected) != 26 or len(names) != 23
            or len(set(names)) != len(names)
            or set(names) | _EXCLUDED != expected
            or set(names) & _EXCLUDED):
        raise ValueError("unreviewed_company_table_inventory")
    return tuple(sorted(names))


def foundation_ddl():
    """Return fixed, audited SQL. Does not connect to or write any database.

    No real company names, users, default grants, ownership backfills,
    changes to existing row contents, RLS policies or enabled UI modes.
    """
    names = private_company_tables()
    sql = [
        'CREATE TABLE "ct_app"."legal_entities" ('
        'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, '
        'code TEXT NOT NULL UNIQUE, legal_name TEXT NOT NULL, '
        'active BOOLEAN NOT NULL DEFAULT TRUE, '
        'CONSTRAINT ct_legal_entity_code_nonempty '
        "CHECK (length(btrim(code)) BETWEEN 2 AND 60))",
        'CREATE TABLE "ct_app"."company_read_grants" ('
        'principal_id TEXT NOT NULL, '
        'legal_entity_id BIGINT NOT NULL REFERENCES "ct_app"."legal_entities"(id), '
        'can_read BOOLEAN NOT NULL DEFAULT FALSE, '
        'PRIMARY KEY (principal_id, legal_entity_id), '
        'CONSTRAINT company_read_grants_principal_nonempty '
        'CHECK (length(btrim(principal_id)) BETWEEN 1 AND 128))',
        'CREATE TABLE "ct_app"."company_write_grants" ('
        'principal_id TEXT NOT NULL, '
        'legal_entity_id BIGINT NOT NULL REFERENCES "ct_app"."legal_entities"(id), '
        'can_write BOOLEAN NOT NULL DEFAULT FALSE, '
        'PRIMARY KEY (principal_id, legal_entity_id), '
        'CONSTRAINT company_write_grants_principal_nonempty '
        'CHECK (length(btrim(principal_id)) BETWEEN 1 AND 128))',
        'CREATE TABLE "ct_app"."company_warehouse_scope" ('
        'warehouse_id BIGINT NOT NULL REFERENCES "ct_app"."warehouses"(id), '
        'legal_entity_id BIGINT NOT NULL REFERENCES "ct_app"."legal_entities"(id), '
        'PRIMARY KEY (warehouse_id,legal_entity_id))',
        'CREATE TABLE "ct_app"."company_operation_audit" ('
        'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, '
        'principal_id TEXT NOT NULL, '
        'legal_entity_id BIGINT NOT NULL REFERENCES "ct_app"."legal_entities"(id), '
        'operation TEXT NOT NULL, target_table TEXT NOT NULL, '
        'record_id BIGINT NOT NULL, '
        'created_at TIMESTAMPTZ NOT NULL DEFAULT now())',
    ]
    for table in names:
        sql.append(
            f'ALTER TABLE "ct_app"."{table}" '
            'ADD COLUMN legal_entity_id BIGINT NULL REFERENCES '
            '"ct_app"."legal_entities"(id)'
        )
        sql.append(
            f'CREATE INDEX "idx_{table}_legal_entity_id" '
            f'ON "ct_app"."{table}" (legal_entity_id)'
        )
    return tuple(sql)


def foundation_status_on_cursor(cur):
    """Read metadata only. Preflight must be clean legacy state, not partial.

    Existing business row contents are irrelevant; no owner is assumed
    and no business row is fetched. A later review must separately reconcile
    counts/owner manifest and security state before any live migration.
    """
    cur.execute(
        "SELECT c.relname, c.relrowsecurity, c.relforcerowsecurity, "
        "EXISTS(SELECT 1 FROM pg_policy p WHERE p.polrelid=c.oid), "
        "EXISTS(SELECT 1 FROM pg_attribute a "
        "WHERE a.attrelid=c.oid AND a.attnum>0 "
        "AND NOT a.attisdropped AND a.attname='legal_entity_id') "
        "FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace "
        "WHERE n.nspname='ct_app' AND c.relkind IN ('r','p') "
        "ORDER BY c.relname"
    )
    rows = cur.fetchall()
    if (len(rows) != 26
            or set(row[0] for row in rows) != _catalog_tables()
            or any(len(row) != 5 or any(type(x) is not bool for x in row[1:])
                   for row in rows)):
        return "schema_mismatch"
    if any(any(row[1:]) for row in rows):
        return "already_migrating"
    cur.execute(
        "SELECT c.relname FROM pg_class c JOIN pg_namespace n "
        "ON n.oid=c.relnamespace WHERE n.nspname='ct_app' "
        "AND c.relname = ANY(%s)",
        (["legal_entities", "company_read_grants", "company_write_grants",
          "company_warehouse_scope", "company_operation_audit"],),
    )
    if cur.fetchall():
        return "already_migrating"
    return "legacy_ready_for_isolated_rehearsal"
